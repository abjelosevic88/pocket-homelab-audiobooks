import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
const require = createRequire(new URL('../web/package.json', import.meta.url))
const { chromium } = require('playwright-core')
const browser = await chromium.connectOverCDP(process.env.CDP)
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
try {
  await context.addCookies([{ name: process.env.PAB_COOKIE_NAME, value: process.env.PAB_COOKIE, url: process.env.BASE, httpOnly: true }])
  await context.addInitScript(() => { const Audio = window.Audio; window.Audio = class extends Audio { constructor(...args) { super(...args); window.__nativeAudio = this } } })
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', e => { errors.push(String(e)); console.error('page error:', String(e)) })
  page.on('console', m => { if(m.type()==='error') console.error('browser:', m.text()) })
  await page.goto(process.env.BASE + '/book/book')
  await page.locator('.book-title').filter({ hasText: 'Native book' }).waitFor()
  await page.getByRole('button', { name: 'Play', exact: true }).first().click()
  await page.waitForFunction(() => { const a = window.__nativeAudio; return a && !a.paused && a.currentTime > 1 })
  await page.getByRole('button', { name: 'Pause', exact: true }).first().click()
  await page.waitForFunction(async () => {
    const me = await fetch('/api/v1/books/book').then(r => r.json())
    return me.book.current_time > 1
  })
  await page.getByRole('button', { name: 'More', exact: true }).click()
  await page.getByText('Edit book', { exact: true }).click()
  await page.getByText('Find metadata', { exact: true }).click()
  await page.getByRole('button', { name: 'Search metadata', exact: true }).click()
  await page.getByRole('button', { name: 'Use this metadata', exact: true }).click()
  await page.waitForFunction(() => [...document.querySelectorAll('input')].some(i => i.value === 'Matched in browser'))
  await page.getByLabel('Cover image', { exact: false }).setInputFiles({ name: 'cover.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAusB9Wl2ZAAAAABJRU5ErkJggg==', 'base64') })
  await page.getByText('Cover saved', { exact: true }).waitFor()
  await page.getByLabel('Title', { exact: true }).fill('Edited in browser')
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  await page.locator('.book-title').filter({ hasText: 'Edited in browser' }).waitFor()
  await page.getByRole('link', { name: 'Read ebook', exact: true }).click()
  await page.waitForFunction(() => [...document.querySelectorAll('button')].some(b=>b.textContent==='Next page'&&!b.disabled), {timeout:15000}).catch(async e=>{console.error(await page.locator('body').innerText());throw e})
  await page.frameLocator('.reader-content iframe').locator('h1').filter({hasText:'Chapter one'}).waitFor()
  assert.equal(await page.evaluate(() => !!window.__ebookAttacked), false)
  const sandbox = await page.locator('.reader-content iframe').getAttribute('sandbox')
  assert.ok(!sandbox.includes('allow-scripts'))
  await page.getByRole('button', { name: 'Next page', exact: true }).click()
  await page.getByRole('status').filter({hasText:'Place saved'}).waitFor()
  const reading = await page.evaluate(() => fetch('/api/v1/catalog/items/book/reader').then(r=>r.json()))
  assert.ok(reading.position.location.startsWith('epubcfi('))
  assert.ok(reading.position.progress > 0)
  await page.reload()
  await page.waitForFunction(() => [...document.querySelectorAll('button')].some(b=>b.textContent==='Next page'&&!b.disabled), {timeout:15000}).catch(async e=>{console.error(await page.locator('body').innerText());throw e})
  const restored = await page.evaluate(() => fetch('/api/v1/catalog/items/book/reader').then(r=>r.json()))
  assert.equal(restored.position.location, reading.position.location)
  await page.getByLabel('Contents', {exact:true}).selectOption('two.xhtml')
  await page.frameLocator('.reader-content iframe').locator('h1').filter({hasText:'Chapter two'}).waitFor()
  await page.getByRole('status').filter({hasText:'Place saved'}).waitFor()
  await page.getByLabel('File', {exact:true}).selectOption('pdf')
  await page.getByRole('status').filter({hasText:'Place saved'}).waitFor()
  await page.getByRole('button', {name:'Next page',exact:true}).click()
  await page.waitForFunction(async () => {
    const r=await fetch('/api/v1/catalog/items/book/reader?file=pdf').then(r=>r.json())
    return r.position.location==='2'
  })
  await page.reload()
  await page.getByLabel('Page', {exact:true}).waitFor()
  assert.equal(await page.getByLabel('Page', {exact:true}).inputValue(), '2')
  await page.locator('.textLayer').getByText('Companion page two', {exact:true}).waitFor()
  await page.goto(process.env.BASE + '/settings/audiobookshelf')
  await page.getByRole('heading', { name: 'Libraries', exact: true }).waitFor()
  await page.getByRole('button', { name: 'Edit access', exact: true }).first().click()
  await page.getByLabel('Account name', { exact: true }).fill('Browser listener')
  await page.getByRole('button', { name: 'Save access', exact: true }).click()
  await page.getByText('Library access saved', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Scan library', exact: true }).click()
  await page.waitForFunction(() => [...document.querySelectorAll('[role="status"]')].some(e => e.textContent.includes('complete')))
  // Upload through the actual web API using a real file, then browse the result.
  const result = await context.request.post(process.env.BASE + '/api/v1/upload', { multipart: {
    library: 'lib', folder: 'folder', title: 'Browser upload', author: 'Browser Author',
    '0': { name: 'Uploaded.mp3', mimeType: 'audio/mpeg', buffer: await readFile(process.env.PAB_UPLOAD) },
  } })
  assert.equal(result.status(), 201, await result.text())
  const uploaded = await result.json()
  await page.goto(process.env.BASE + '/book/' + uploaded.id)
  await page.locator('.book-title').filter({ hasText: 'Browser upload' }).waitFor()
  await page.getByRole('button', { name: 'More', exact: true }).click()
  await page.getByText('Add to a list', { exact: true }).click()
  await page.getByLabel('New list name', { exact: true }).fill('Browser collection')
  await page.getByRole('button', { name: 'Create and add book', exact: true }).click()
  await page.getByText('Book added', { exact: true }).waitFor()
  await page.goto(process.env.BASE + '/lists')
  await page.getByRole('heading', { name: 'Browser collection', exact: true }).waitFor()
  await page.getByRole('button', { name: 'Edit list', exact: true }).click()
  await page.getByLabel('List name', { exact: true }).fill('Renamed collection')
  await page.getByRole('button', { name: 'Save list', exact: true }).click()
  await page.getByRole('heading', { name: 'Renamed collection', exact: true }).waitFor()
  await page.goto(process.env.BASE + '/podcasts')
  await page.getByText('Subscribe or import', { exact: true }).click()
  await page.getByLabel('RSS or Atom feed URL', { exact: true }).fill('http://podcast.test/feed.xml')
  await page.getByRole('button', { name: 'Subscribe', exact: true }).click()
  await page.getByRole('heading', { name: 'Browser podcast', exact: true }).waitFor()
  await page.getByRole('button', { name: 'Download episode', exact: true }).click()
  await page.getByRole('button', { name: 'Play episode', exact: true }).click({ timeout: 25000 })
  await page.waitForFunction(() => {const a=window.__nativeAudio; return a && !a.paused && a.currentTime>0.5})
  await page.getByRole('button', { name: 'Pause', exact: true }).first().click()
  await page.waitForFunction(async () => {
    const id=location.pathname.split('/').pop()
    const info=await fetch('/api/v1/podcasts/'+id).then(r=>r.json())
    const book=await fetch('/api/v1/podcasts/'+id+'/episodes/'+info.episodes[0].id).then(r=>r.json())
    return book.book.current_time>0.5
  })
  await page.reload()
  await page.waitForFunction(() => [...document.querySelectorAll('.pb-title')].some(e=>e.textContent.includes('Browser episode')) || navigator.mediaSession?.metadata?.title==='Browser episode')
  assert.deepEqual(errors, [])
  console.log('Native browser acceptance passed: play, pause/save, metadata search/edit, scan, upload, browse, account access, collections, podcast subscription/download/play/resume, EPUB reading/resume/chapters, companion PDF paging/resume.')
} finally { await context.close(); await browser.close() }
